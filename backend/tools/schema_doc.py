"""Generate docs/DATABASE.md (the data dictionary) from the SQLAlchemy models.

    uv run python -m tools.schema_doc
"""
from collections import defaultdict
from pathlib import Path

from sqlalchemy.dialects import postgresql

import app.models  # noqa: F401
from app.db.base import Base

OUT = Path(__file__).resolve().parents[2] / "docs" / "DATABASE.md"
PIPE = "\\|"

INTRO = """# Database reference

Generated by `uv run python -m tools.schema_doc` — do not edit by hand. {n} tables in PostgreSQL (Supabase).

## Conventions
* Names: `snake_case`, singular nouns (`student`, `employee_assignment`); primary key `<table>_id`; foreign keys keep the
  referenced key's name (`campus_id`). Soft/optional owners are nullable FKs.
* Every timestamp is `timestamptz`; `created_at`/`updated_at` are `NOT NULL DEFAULT now()`.
* Editable business records carry an integer `version` (optimistic concurrency) and, where they are people-facing,
  `deleted_at` for soft delete. Audit columns point at `user_account`.
* Constraint and index names are normalised centrally (`app/db/naming.py`): `ix_<table>_<cols>`, `uq_<table>_<cols>`,
  `ck_<table>_<rule>`, foreign keys `fk_<table>_<cols>_<target>`. Every foreign key is indexed (enforced by a test).
* Row level security is **on for every table**; only the API's database role can read or write (see SECURITY.md).
* Append-only (trigger-enforced): `audit_log`, `status_history`, `evidence_document_audit`, `consultancy_receipt`,
  `consultancy_receipt_void`, `research_utilization_void`.
* Platform tables (not business data): `auth_session`, `audit_log`, `status_history`, `job`, `job_schedule`,
  `idempotency_key`, `rate_limit_bucket`, `notification`.

## Adding or changing tables
1. Edit the model in `backend/app/models/<domain>.py` (follow the existing naming).
2. `uv run alembic revision --autogenerate -m "describe change"`, review the generated file, add
   `ALTER TABLE ... ENABLE ROW LEVEL SECURITY` for any new table, apply with `uv run python -m app.cli migrate`.
3. `uv run pytest tests/test_schema_quality.py tests/test_migrations.py` must pass; regenerate this file.
"""


def type_name(col) -> str:
    return str(col.type.compile(dialect=postgresql.dialect())).lower()


def main() -> None:
    by_module: dict[str, list] = defaultdict(list)
    classes = {m.local_table.name: m.class_ for m in Base.registry.mappers}
    for t in Base.metadata.sorted_tables:
        mod = classes[t.name].__module__.rsplit(".", 1)[-1] if t.name in classes else "other"
        by_module[mod].append(t)
    lines = [INTRO.format(n=len(Base.metadata.tables))]
    for mod in sorted(by_module):
        lines.append("\n## " + mod.replace("_", " ").title() + "\n")
        for t in sorted(by_module[mod], key=lambda x: x.name):
            lines.append(f"### `{t.name}`\n")
            lines.append("| Column | Type | Null | Default | Notes |\n| --- | --- | --- | --- | --- |")
            fks = {c.parent.name: f"-> `{c.column.table.name}.{c.column.name}`" for c in t.foreign_keys}
            for c in t.columns:
                notes = []
                if c.primary_key:
                    notes.append("PK")
                if c.name in fks:
                    notes.append(fks[c.name])
                default = "" if c.server_default is None else str(getattr(c.server_default, "arg", c.server_default)).replace("|", PIPE)
                lines.append(f"| `{c.name}` | {type_name(c)} | {'yes' if c.nullable else 'no'} | {default} | {' '.join(notes)} |")
            uniq = [", ".join(col.name for col in u.columns) for u in t.constraints if u.__class__.__name__ == "UniqueConstraint"]
            if uniq:
                lines.append("\nUnique: " + "; ".join(f"({u})" for u in uniq))
            lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf8")
    print(f"wrote {OUT} ({len(Base.metadata.tables)} tables)")


if __name__ == "__main__":
    main()
