CREATE TABLE faculty_course_assignment (
    version BIGINT UNSIGNED NOT NULL DEFAULT 1,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    created_by_id BIGINT NOT NULL,
    updated_by_id BIGINT NOT NULL,
    CONSTRAINT fk_m8_0_creator FOREIGN KEY (created_by_id) REFERENCES user_account(user_id),
    CONSTRAINT fk_m8_0_editor FOREIGN KEY (updated_by_id) REFERENCES user_account(user_id),
    CONSTRAINT chk_m8_assignment_dates CHECK (end_date IS NULL OR end_date >= start_date),
    CONSTRAINT chk_m8_workload CHECK (workload_hours IS NULL OR workload_hours > 0),
    CONSTRAINT uq_m8_faculty_section UNIQUE (faculty_assignment_id, course_offering_section_id),
    INDEX ix_m8_employee_dates (employee_id, assignment_status, start_date, end_date),
    faculty_assignment_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    course_offering_section_id BIGINT UNSIGNED NOT NULL,
    employee_id BIGINT UNSIGNED NOT NULL,
    assignment_role ENUM('PRIMARY_INSTRUCTOR','CO_INSTRUCTOR','LAB_INSTRUCTOR','TUTOR','COORDINATOR','OTHER') NOT NULL,
    workload_hours DECIMAL(6,2) NULL,
    start_date DATE NOT NULL,
    end_date DATE NULL,
    assignment_status ENUM('PLANNED','ACTIVE','COMPLETED','CANCELLED') NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT uq_faculty_course_assignment UNIQUE (course_offering_section_id, employee_id, assignment_role, start_date),
    CONSTRAINT fk_faculty_assignment_section FOREIGN KEY (course_offering_section_id) REFERENCES course_offering_section(course_offering_section_id),
    CONSTRAINT fk_faculty_assignment_employee FOREIGN KEY (employee_id) REFERENCES employee(employee_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE timetable_session (
    version BIGINT UNSIGNED NOT NULL DEFAULT 1,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    created_by_id BIGINT NOT NULL,
    updated_by_id BIGINT NOT NULL,
    CONSTRAINT fk_m8_1_creator FOREIGN KEY (created_by_id) REFERENCES user_account(user_id),
    CONSTRAINT fk_m8_1_editor FOREIGN KEY (updated_by_id) REFERENCES user_account(user_id),
    CONSTRAINT chk_m8_session_dates CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CONSTRAINT fk_m8_session_faculty_owner FOREIGN KEY (faculty_assignment_id, course_offering_section_id)
        REFERENCES faculty_course_assignment(faculty_assignment_id, course_offering_section_id),
    INDEX ix_m8_section_interval (course_offering_section_id, day_of_week, effective_from, effective_to),
    INDEX ix_m8_faculty_interval (faculty_assignment_id, day_of_week, effective_from, effective_to),
    timetable_session_id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    course_offering_section_id BIGINT UNSIGNED NOT NULL,
    faculty_assignment_id BIGINT UNSIGNED NULL,
    day_of_week TINYINT UNSIGNED NOT NULL,
    time_slot_id SMALLINT UNSIGNED NOT NULL,
    room_id INT UNSIGNED NULL,
    effective_from DATE NOT NULL,
    effective_to DATE NULL,
    CONSTRAINT chk_day_of_week CHECK (day_of_week BETWEEN 1 AND 7),
    INDEX ix_m8_room_interval (room_id, day_of_week, effective_from, effective_to, time_slot_id),
    CONSTRAINT fk_timetable_section FOREIGN KEY (course_offering_section_id) REFERENCES course_offering_section(course_offering_section_id),
    CONSTRAINT fk_timetable_faculty FOREIGN KEY (faculty_assignment_id) REFERENCES faculty_course_assignment(faculty_assignment_id),
    CONSTRAINT fk_timetable_time_slot FOREIGN KEY (time_slot_id) REFERENCES time_slot(time_slot_id),
    CONSTRAINT fk_timetable_room FOREIGN KEY (room_id) REFERENCES room(room_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
